"""Enumerate bijunctive relations on small cubes and check their parity classes."""

from collections import Counter, defaultdict
from itertools import combinations, product


def popcount(n):
    return bin(n).count('1')


def words(mask):
    while mask:
        bit = mask & -mask
        yield bit.bit_length() - 1
        mask ^= bit


def relation(set_of_words):
    return sum(1 << w for w in set_of_words)


def forbidden_cells(n):
    """Each cell is the set falsifying one clause of width one or two."""
    cube = range(1 << n)
    cells = []
    for k in (1, 2):
        for sites in combinations(range(n), k):
            for bits in product((0, 1), repeat=k):
                cells.append(relation(w for w in cube
                                      if all(((w >> i) & 1) == b for i, b in zip(sites, bits))))
    return cells


def all_relations(full, cells):
    """Closure system generated by successively conjoining each possible clause."""
    relations = {full}
    for cell in cells:
        relations |= {r & ~cell for r in relations}
    return relations


def two_cnf_hull(r, full, cells):
    """Models of ALL binary and unit clauses valid on r."""
    hull = full
    for cell in cells:
        if not r & cell:
            hull &= ~cell
    return hull


def perfect_pairings(coords):
    if not coords:
        yield ()
        return
    first, *rest = coords
    for j, second in enumerate(rest):
        for pairs in perfect_pairings(rest[:j] + rest[j+1:]):
            yield ((first, second),) + pairs


def pair_relations(n):
    """Independent construction of all disjoint equality/disequality patterns."""
    cases = []
    for pin in range(n) if n % 2 else [None]:
        coords = [i for i in range(n) if i != pin]
        for pairs in perfect_pairings(coords):
            for sides in product((0, 1), repeat=len(pairs)):
                for val in ((0, 1) if pin is not None else (None,)):
                    cases.append(relation(w for w in range(1 << n)
                        if (pin is None or ((w >> pin) & 1) == val)
                        and all((((w >> i) ^ (w >> j)) & 1) == s
                                for (i, j), s in zip(pairs, sides))))
    assert len(set(cases)) == len(cases)
    return set(cases)


def check_one(r, n, pairs):
    """Check the structure of the transported span, not only its dimension."""
    assignments = list(words(r))
    a = assignments[0]
    translated = {a ^ w for w in assignments}
    assert all((x & y) in translated for x in translated for y in translated)
    blocks = defaultdict(int)
    for i in range(n):
        column = tuple((w >> i) & 1 for w in sorted(translated))
        if any(column):
            blocks[column] |= 1 << i
    assert all(popcount(block) % 2 == 0 for block in blocks.values())
    unions = {0}
    for block in blocks.values():
        unions |= {x | block for x in unions}
    span = {0}
    for v in translated:
        span |= {x ^ v for x in span}
    assert span == unions
    assert any(r & ~pattern == 0 for pattern in pairs)
    assert len(translated) <= 1 << (n // 2)
    assert (len(translated) == 1 << (n // 2)) == (r in pairs)


def subsets(mask):
    p = mask
    while p:
        yield p
        p = (p - 1) & mask


def main():
    for n in range(1, 6):
        full = (1 << (1 << n)) - 1
        cells = forbidden_cells(n)
        parity = [relation(w for w in range(1 << n) if popcount(w) % 2 == bit)
                  for bit in (0, 1)]
        pairs = pair_relations(n)
        if n <= 4:
            family = all_relations(full, cells)
            assert family == {r for r in range(full+1) if two_cnf_hull(r, full, cells) == r}
            scope = f"{len(family)} distinct 2-CNF relations"
        else:
            family = None
            scope = "every nonempty monochromatic relation tested for 2-CNF definability"
        for bit, par in enumerate(parity):
            if family is None:
                mono = {r for r in subsets(par) if two_cnf_hull(r, full, cells) == r}
            else:
                mono = {r for r in family if r and not r & ~par}
            for r in mono:
                check_one(r, n, pairs)
            hist = Counter(popcount(r) for r in mono)
            largest = {r for r in mono if popcount(r) == 1 << (n//2)}
            assert largest == {r for r in pairs if not r & ~par}
            print(f"n={n} parity={bit} nonempty={len(mono)} maximal-size={max(hist)}"
                  f" equality-patterns={len(largest)}")
        print(f"PASS n={n}: {scope}")


if __name__ == "__main__":
    main()
